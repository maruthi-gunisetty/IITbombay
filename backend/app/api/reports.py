import os
import uuid
from typing import Optional, Dict, Any
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse
from backend.app.api.deps import get_current_user, record_audit
from backend.app.services.report_service import report_service, REPORTS_DIR
from backend.app.database.repo import repo

router = APIRouter(prefix="/reports", tags=["Reports & Insights"])

@router.get("")
def list_reports(
    report_type: Optional[str] = None,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    return repo.list_reports(report_type=report_type)

@router.post("")
def generate_report(
    payload: dict,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    report_type = payload.get("report_type", "Property Valuation Report")
    title = payload.get("title", f"Institutional Assessment Dossier: {report_type}")
    reference_id = payload.get("reference_id", f"REF-{uuid.uuid4().hex[:6].upper()}")
    summary = payload.get("summary", "Automated executive summary generated by Gruha Anwesh Intelligence engine.")
    details = payload.get("details", {})
    report_no = f"REP-2026-{uuid.uuid4().hex[:6].upper()}"

    # Generate genuine PDF with ReportLab
    pdf_filename = report_service.generate_pdf(
        report_title=title,
        report_number=report_no,
        generated_by=current_user.get("full_name", "Officer"),
        summary=summary,
        details=details
    )

    record = repo.create_report({
        "report_number": report_no,
        "report_type": report_type,
        "title": title,
        "reference_id": reference_id,
        "generated_by": current_user.get("full_name", "Officer"),
        "summary": summary,
        "details": details,
        "pdf_filename": pdf_filename
    })

    repo.create_notification(
        user_id=current_user["id"],
        category="Report",
        title="Institutional Dossier Generated",
        message=f"{report_no} ({title}) ready for PDF download.",
        link="/dashboard/reports"
    )

    record_audit(current_user, "REPORT_GENERATED", "ReportRecord", str(record["id"]), f"Generated {report_no}")
    return record

@router.get("/{id}/download")
def download_report_pdf(
    id: int,
    current_user: Dict[str, Any] = Depends(get_current_user)
):
    record = repo.get_report(id)
    if not record or not record.get("pdf_filename"):
        raise HTTPException(status_code=404, detail="Report PDF not found")

    file_path = os.path.join(REPORTS_DIR, record["pdf_filename"])
    if not os.path.exists(file_path):
        new_pdf = report_service.generate_pdf(
            report_title=record["title"],
            report_number=record["report_number"],
            generated_by=record["generated_by"],
            summary=record["summary"],
            details=record.get("details", {})
        )
        record["pdf_filename"] = new_pdf
        file_path = os.path.join(REPORTS_DIR, new_pdf)

    record_audit(current_user, "REPORT_DOWNLOADED", "ReportRecord", str(id), f"Downloaded {record['report_number']}")

    return FileResponse(
        path=file_path,
        filename=f"{record['report_number']}.pdf",
        media_type="application/pdf"
    )
