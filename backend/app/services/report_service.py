import os
import uuid
from typing import Dict, Any
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from backend.app.core.config import settings

REPORTS_DIR = os.path.join(settings.UPLOAD_DIR, "reports")
os.makedirs(REPORTS_DIR, exist_ok=True)

class ReportService:
    @staticmethod
    def generate_pdf(
        report_title: str,
        report_number: str,
        generated_by: str,
        summary: str,
        details: Dict[str, Any]
    ) -> str:
        """Generates a professional enterprise PDF document and returns the saved filename."""
        filename = f"report_{report_number}_{uuid.uuid4().hex[:6]}.pdf"
        filepath = os.path.join(REPORTS_DIR, filename)

        doc = SimpleDocTemplate(
            filepath,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40
        )
        story = []
        styles = getSampleStyleSheet()

        # Custom Enterprise FinTech Styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#080E1B"),
            fontName="Helvetica-Bold",
            spaceAfter=6
        )
        tagline_style = ParagraphStyle(
            "Tagline",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#3978F6"),
            fontName="Helvetica-Bold",
            spaceAfter=15
        )
        section_style = ParagraphStyle(
            "SectionHeader",
            parent=styles["Heading2"],
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#2457C5"),
            fontName="Helvetica-Bold",
            spaceBefore=14,
            spaceAfter=8
        )
        body_style = ParagraphStyle(
            "Body",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#23324A"),
            spaceAfter=10
        )

        # Header Block
        story.append(Paragraph("PROPWISE AI", title_style))
        story.append(Paragraph("Smarter Property Valuation. Safer Lending Decisions.", tagline_style))
        story.append(Spacer(1, 10))

        # Metadata Table
        meta_data = [
            ["Dossier Title:", report_title, "Report Reference:", report_number],
            ["Generated By:", generated_by, "Date:", "16 November 2026"],
            ["Verification Engine:", "PropWise v3.1 Enterprise", "Policy Clearance:", "Decision Support Support Only"]
        ]
        meta_table = Table(meta_data, colWidths=[120, 160, 120, 130])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F5F7FC")),
            ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor("#080E1B")),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('FONTNAME', (2, 0), (2, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#23324A")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 15))

        # Executive Summary
        story.append(Paragraph("1. Executive Intelligence Summary", section_style))
        story.append(Paragraph(summary, body_style))
        story.append(Spacer(1, 10))

        # Technical Key-Value Metrics Table
        story.append(Paragraph("2. Assessment Details & Parameters", section_style))
        detail_rows = [["Evaluation Parameter", "Observed Value / Rating"]]
        for k, v in details.items():
            if isinstance(v, (dict, list)):
                continue
            detail_rows.append([str(k).replace("_", " ").title(), str(v)])

        if len(detail_rows) > 1:
            detail_table = Table(detail_rows, colWidths=[240, 290])
            detail_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#3978F6")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('FONTSIZE', (0, 0), (-1, -1), 9),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#23324A")),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ('TOPPADDING', (0, 0), (-1, -1), 5),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
            ]))
            story.append(detail_table)

        # Regulatory Notice Footer
        story.append(Spacer(1, 20))
        story.append(Paragraph("3. Regulatory & Human Review Safeguard", section_style))
        notice_text = (
            "NOTICE: This automated report is generated strictly for financial institutional decision support. "
            "Under enterprise policy and prudent credit risk standards, all mortgage sanction and property acquisition "
            "commitments require final affirmative verification and authorization by a certified human lending officer."
        )
        story.append(Paragraph(notice_text, body_style))

        doc.build(story)
        return filename

report_service = ReportService()
